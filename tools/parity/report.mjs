import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { DECISIONS } from './expected.mjs';
import { root } from './servers.mjs';

const cell = (text) => String(text).replaceAll('|', '\\|');

const details = (rows) => rows.flatMap((row) => {
  const lines = [...row.problems.map((p) => `- **${p}**`), ...row.values.map((v) => `- value: \`${cell(v)}\``)];
  return lines.length ? [`### ${row.name}`, '', ...lines, ''] : [];
});

const expectedValues = (rows) => rows.filter((row) => row.expectedValues?.values.length).flatMap((row) => [
  `- **${row.name}** — ${row.expectedValues.note}`,
  ...row.expectedValues.values.map((v) => `  - \`${cell(v)}\``),
]);

/** Writes docs/PARITY.md and returns the number of steps that differ. */
export const writeReport = (rows, { source }) => {
  const failed = rows.filter((row) => !row.ok).length;
  const ordered = rows.filter((row) => row.order.length).map((row) => `- ${row.name}: ${row.order.join('; ')}`);
  const lines = [
    '# Parity report: legacy Node backend vs Spring Boot backend',
    '',
    `Generated by \`npm run parity\` (tools/parity) on ${new Date().toISOString().slice(0, 10)}, against the ${source}.`,
    'Both backends ran their E2E configuration (seeded problems, fake Codeforces, fake AI, separate databases) and',
    'got the same request sequence; the legacy answers were recorded live (tools/parity/legacy-snapshot.json) before',
    'the legacy code was removed. Compared: status code, error code and JSON shape (keys and value types).',
    'Values are compared too, with ids, tokens, request ids, timestamps and uptime masked.',
    '',
    `**Result: ${failed ? `${failed} of ${rows.length} steps differ` : `clean — all ${rows.length} steps match`}.**`,
    '',
    '| # | Step | Legacy | Spring | Match | ms (legacy / spring) |',
    '|---|---|---|---|---|---|',
    ...rows.map((row, i) => `| ${i + 1} | ${cell(row.name)} | ${row.legacy} | ${row.spring} | ${row.ok ? 'yes' : '**no**'} `
      + `| ${row.ms.map((ms) => ms ?? '-').join(' / ')} |`),
    '',
    '## Differences',
    '',
    ...(failed ? details(rows.filter((row) => !row.ok)) : ['None.', '']),
    '## Expected differences (deliberate decisions)',
    '',
    ...DECISIONS.map(([title, text]) => `- **${title}.** ${text}`),
    ...(expectedValues(rows).length ? ['', 'Value differences explained by those decisions:', '', ...expectedValues(rows)] : []),
    '',
    '## Key order (informational)',
    '',
    ...(ordered.length ? ordered : ['Same key order in every response.']),
    '',
  ];
  writeFileSync(path.join(root, 'docs/PARITY.md'), lines.join('\n'));
  return failed;
};
